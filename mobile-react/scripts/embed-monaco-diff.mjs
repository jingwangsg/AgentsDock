import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const entry = resolve(root, 'scripts/monaco-diff-entry.ts')
const target = resolve(root, 'src/editor/monacoDiffAssets.ts')
const check = process.argv.includes('--check')

const { version } = JSON.parse(await readFile(resolve(root, 'node_modules/monaco-editor/package.json'), 'utf8'))
const buildResult = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  // Monaco's modules import their CSS; esbuild only splits it into a sibling
  // output when it has an output path, so name one. Nothing is written.
  outdir: resolve(root, 'scripts/.monaco-diff-build'),
  format: 'iife',
  platform: 'browser',
  target: ['safari16.4'],
  minify: true,
  charset: 'utf8',
  legalComments: 'eof',
  sourcemap: false,
  logLevel: 'silent',
})

const scriptOutput = buildResult.outputFiles.find(file => file.path.endsWith('.js'))
const styleOutput = buildResult.outputFiles.find(file => file.path.endsWith('.css'))
if (!scriptOutput || !styleOutput) throw new Error('The Monaco bundle did not produce both JavaScript and CSS output.')
const script = scriptOutput.text.replace(/<\/script/gi, '<\\/script')
// The CSS is inlined verbatim into one <style>; a closing tag inside it would end the sheet early.
if (/<\/style/i.test(styleOutput.text)) throw new Error('The Monaco CSS contains "</style"; the inline embedding needs escaping before it can ship.')
// editor.api does not register the codicon icon font (that is features/codicon,
// part of editor.main), and a read-only diff editor without the folding and
// revert contribs shows no icon glyphs, so the page ships no font at all.
if (/@font-face/i.test(styleOutput.text)) throw new Error('The Monaco CSS now declares a font; inline it as a data URL and allow font-src before shipping.')
const scriptHash = createHash('sha256').update(script).digest()
const csp = [
  "default-src 'none'",
  `script-src 'sha256-${scriptHash.toString('base64')}'`,
  "style-src 'unsafe-inline'",
  "connect-src 'none'",
  // Monaco builds some decoration styles at runtime with data: images; still offline.
  "img-src data:",
  "media-src 'none'",
  "font-src 'none'",
  "object-src 'none'",
  "frame-src 'none'",
  "worker-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ')
// Gap rows and merge-conflict rows mirror electron/src/renderer/src/styles.css
// (.review-monaco-*); colours come from src/theme.ts (selected / muted) and the
// desktop review panel's conflict palette, which keeps the three sides distinct.
const appStyle = [
  'html,body,#editor{width:100%;height:100%;margin:0;padding:0;overflow:hidden;background:transparent}',
  'body{overscroll-behavior:none;-webkit-text-size-adjust:100%;-webkit-touch-callout:none}',
  '*{box-sizing:border-box}',
  'body[data-theme=dark]{--gap-bg:#454a56;--muted:#a9afbc;--conflict-ours:#58a6ff;--conflict-base:#e3b341;--conflict-theirs:#bc8cff}',
  'body[data-theme=light]{--gap-bg:#cacaca;--muted:#58585a;--conflict-ours:#0969da;--conflict-base:#7d4e00;--conflict-theirs:#6639ba}',
  '.review-monaco-gap{background:var(--gap-bg)}',
  '.review-monaco-gap-text{color:var(--muted);font-style:italic}',
  '.review-monaco-conflict.ours{--conflict-side-color:var(--conflict-ours)}',
  '.review-monaco-conflict.base{--conflict-side-color:var(--conflict-base)}',
  '.review-monaco-conflict.theirs{--conflict-side-color:var(--conflict-theirs)}',
  '.review-monaco-conflict{background:color-mix(in srgb,var(--conflict-side-color) 13%,transparent);box-shadow:inset 3px 0 var(--conflict-side-color)}',
  '.review-monaco-conflict-marker{font-weight:650}',
].join('')
const htmlPrefix = [
  '<!doctype html>',
  '<html>',
  '<head>',
  '<meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">',
  `<meta http-equiv="Content-Security-Policy" content="${csp}">`,
  `<style>${styleOutput.text}</style>`,
  `<style>${appStyle}</style>`,
  '</head>',
  '<body data-theme="dark">',
  '<div id="editor"></div>',
  '<script>',
].join('')
const htmlSuffix = '</script></body></html>'
const generated = [
  '// Generated by scripts/embed-monaco-diff.mjs. Do not edit by hand.',
  `export const MONACO_DIFF_VERSION = ${JSON.stringify(version)}`,
  `export const MONACO_DIFF_ASSET_SHA256 = ${JSON.stringify(scriptHash.toString('hex'))}`,
  // One literal: Metro constant-folds a SCRIPT + HTML form and stores the
  // program twice in Hermes bytecode.
  `export const MONACO_DIFF_HTML = ${JSON.stringify(`${htmlPrefix}${script}${htmlSuffix}`)}`,
  '',
].join('\n')

const existing = await readFile(target, 'utf8').catch(() => null)
if (check) {
  if (existing !== generated) {
    console.error('Generated Monaco diff assets are stale. Run: node scripts/embed-monaco-diff.mjs')
    process.exitCode = 1
  }
} else if (existing !== generated) {
  await mkdir(dirname(target), { recursive: true })
  await writeFile(target, generated)
}
